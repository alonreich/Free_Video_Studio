using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;

namespace FreeVideoStudio.Core.Media;

/// <summary>
/// AICAPTION_ASS_01 — Advanced SubStation Alpha (.ass v4.00+) writer for live commentary captions.
/// Generates styled, karaoke-animated subtitles with exact positioning, \k centisecond highlight tags,
/// and safe character escaping for direct consumption by FFmpeg (subtitles filter) and libmpv (sub-add).
/// </summary>
public static class CaptionAssWriter
{
    public const string DefaultFontName = "Arial";

    // Primary: bright white text; Secondary (unhighlighted karaoke): light muted silver; Outline & Shadow: deep black
    public const string PrimaryColourDefault = "&H00FFFFFF";
    public const string SecondaryColourKaraoke = "&H00A0A0A0";
    public const string OutlineColourDefault = "&H00000000";
    public const string BackColourDefault = "&H80000000";
    public const string EmphasisColourDefault = "&H0000E5FF"; // Bright gaming gold / yellow

    /// <summary>
    /// Generates full .ass script text from a <see cref="CaptionTrack"/> and an optional <see cref="OutputTimeline"/>.
    /// </summary>
    public static string GenerateAss(
        CaptionTrack track,
        OutputTimeline? timeline = null,
        int outputW = 1080,
        int outputH = 1920,
        bool isPortrait = true,
        IReadOnlyList<(double X, double Y, double W, double H)>? hudRects = null,
        string fontName = DefaultFontName,
        double baseOffsetSec = 0.0)
    {
        var mappedLines = CaptionTimeline.Map(track, timeline, baseOffsetSec);
        var sb = new StringBuilder();

        // 1. Script Info
        sb.AppendLine("[Script Info]");
        sb.AppendLine("; Script generated by Free Video Studio AI Live Commentary Engine");
        sb.AppendLine("Title: Free Video Studio AI Live Commentary Captions");
        sb.AppendLine("ScriptType: v4.00+");
        sb.AppendLine("WrapStyle: 0");
        sb.AppendLine($"PlayResX: {outputW}");
        sb.AppendLine($"PlayResY: {outputH}");
        sb.AppendLine("ScaledBorderAndShadow: yes");
        sb.AppendLine();

        // 2. V4+ Styles
        int baseFontSize = isPortrait ? 54 : 58;
        sb.AppendLine("[V4+ Styles]");
        sb.AppendLine("Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding");

        // Main Commentary Style
        // Alignment 2 = bottom-center, 8 = top-center
        int alignCode = track.Position == CaptionPosition.Top ? 8 : 2;
        sb.Append($"Style: Commentary,{fontName},{baseFontSize},");
        sb.Append($"{PrimaryColourDefault},{SecondaryColourKaraoke},{OutlineColourDefault},{BackColourDefault},");
        sb.AppendLine($"-1,0,0,0,100,100,0,0,1,3.5,2.0,{alignCode},40,40,40,1");
        sb.AppendLine();

        // 3. Events
        sb.AppendLine("[Events]");
        sb.AppendLine("Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text");

        foreach (var mapped in mappedLines)
        {
            var layout = CaptionLayoutEngine.ComputeLayout(
                mapped, outputW, outputH, isPortrait, track.Position, hudRects, fontName);

            if (layout.Lines.Count == 0) continue;

            string startStr = FormatAssTimestamp(layout.OutputStartSec);
            string endStr = FormatAssTimestamp(layout.OutputEndSec);

            string dialogueText = BuildDialogueText(layout, track.Style);

            sb.AppendLine($"Dialogue: 0,{startStr},{endStr},Commentary,,0,0,0,,{dialogueText}");
        }

        return sb.ToString();
    }

    /// <summary>
    /// Formats seconds into ASS timestamp standard: H:MM:SS.cc (e.g. 0:01:23.45).
    /// </summary>
    public static string FormatAssTimestamp(double totalSec)
    {
        if (totalSec < 0) totalSec = 0;
        var ts = TimeSpan.FromSeconds(totalSec);
        int hours = (int)ts.TotalHours;
        int minutes = ts.Minutes;
        int seconds = ts.Seconds;
        int centis = (int)Math.Clamp(Math.Round(ts.Milliseconds / 10.0), 0, 99);
        return $"{hours}:{minutes:D2}:{seconds:D2}.{centis:D2}";
    }

    /// <summary>
    /// Escapes special ASS characters in text: { } \ and converts internal newlines to \N.
    /// </summary>
    public static string EscapeAssText(string text)
    {
        if (string.IsNullOrEmpty(text)) return string.Empty;

        var sb = new StringBuilder(text.Length + 8);
        for (int i = 0; i < text.Length; i++)
        {
            char c = text[i];
            switch (c)
            {
                case '\\':
                    sb.Append(@"\\");
                    break;
                case '{':
                    sb.Append(@"\{");
                    break;
                case '}':
                    sb.Append(@"\}");
                    break;
                case '\n':
                    sb.Append(@"\N");
                    break;
                case '\r':
                    // Drop CR
                    break;
                default:
                    sb.Append(c);
                    break;
            }
        }
        return sb.ToString();
    }

    private static string BuildDialogueText(CaptionLayout layout, CaptionStyle style)
    {
        var lineParts = new List<string>(layout.Lines.Count);

        for (int i = 0; i < layout.Lines.Count; i++)
        {
            var line = layout.Lines[i];
            var wordParts = new List<string>(line.Words.Count);

            foreach (var w in line.Words)
            {
                string safeText = EscapeAssText(w.Text);

                if (style == CaptionStyle.Karaoke)
                {
                    if (w.IsEmphasized)
                    {
                        // Emphasized word: switch color to gold/yellow during karaoke sweep
                        wordParts.Add(@$"{{\c{EmphasisColourDefault}&\k{w.DurationCentisec}}}{safeText}{{\c{PrimaryColourDefault}&}}");
                    }
                    else
                    {
                        wordParts.Add(@$"{{\k{w.DurationCentisec}}}{safeText}");
                    }
                }
                else
                {
                    // Pop-in / plain text style
                    if (w.IsEmphasized)
                        wordParts.Add(@$"{{\c{EmphasisColourDefault}&}}{safeText}{{\c{PrimaryColourDefault}&}}");
                    else
                        wordParts.Add(safeText);
                }
            }

            lineParts.Add(string.Join(" ", wordParts));
        }

        // Exact pixel positioning override with \pos(x, y) if positioned, or bottom-center
        double centerX = Math.Round(layout.BoxX + (layout.BoxWidth / 2.0));
        double centerY = Math.Round(layout.BoxY + (layout.BoxHeight / 2.0));

        string content = string.Join(@"\N", lineParts);
        return @$"{{\pos({centerX.ToString(CultureInfo.InvariantCulture)},{centerY.ToString(CultureInfo.InvariantCulture)})}}{content}";
    }

    /// <summary>
    /// Writes the generated ASS subtitle script directly to a file.
    /// </summary>
    public static void WriteToFile(
        string filePath,
        CaptionTrack track,
        OutputTimeline? timeline = null,
        int outputW = 1080,
        int outputH = 1920,
        bool isPortrait = true,
        IReadOnlyList<(double X, double Y, double W, double H)>? hudRects = null,
        string fontName = DefaultFontName,
        double baseOffsetSec = 0.0)
    {
        ArgumentNullException.ThrowIfNull(filePath);
        string text = GenerateAss(track, timeline, outputW, outputH, isPortrait, hudRects, fontName, baseOffsetSec);
        string dir = Path.GetDirectoryName(filePath) ?? "";
        if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir)) Directory.CreateDirectory(dir);
        File.WriteAllText(filePath, text, Encoding.UTF8);
    }
}
